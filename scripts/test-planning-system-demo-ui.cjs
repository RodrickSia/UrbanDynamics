const {chromium}=require('../.runtime/ui-check/node_modules/playwright-core');
const assert=require('node:assert/strict');
const fs=require('node:fs');
(async()=>{
  const out='test-results/planning-system-demo';
  const native=JSON.parse(fs.readFileSync(out+'/http-report.json','utf8'));
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const checks=[];
  try{
    const page=await browser.newPage({viewport:{width:1360,height:980}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:8007/simulation/planning');
    await page.locator('#system-demo').waitFor({state:'visible'});
    await page.locator('#system-load').click();
    await page.waitForFunction(()=>document.querySelector('#system-parcels').options.length===200);
    assert.equal(await page.locator('#system-parcel-map path').count(),200);
    await page.locator(`#system-parcel-map path[data-parcel="${native.parcel_id}"]`).dispatchEvent('click');
    assert.deepEqual(await page.locator('#system-parcels').evaluate(el=>Array.from(el.selectedOptions,o=>o.value)),[String(native.parcel_id)]);
    checks.push('200 sourced parcels rendered and polygon selection binds actual parcel ID');
    await page.locator('#system-prepare').click();
    await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Đã nối parcel'));
    const input=JSON.parse(await page.locator('#input').inputValue());
    assert.equal(input.data_mode,'demo_system');
    assert.equal(input.system_snapshot_id,native.snapshot_id);
    assert.equal(input.system_parcel_bindings.P1,String(native.parcel_id));
    await page.locator('#preflight').click();
    await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Sẵn sàng:'));
    checks.push('Building-plan preparation and preflight use frozen system snapshot');
    await page.locator('#run').click();
    await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Hoàn thành và lưu'),{},{timeout:45000});
    assert.match(await page.locator('#manifest-summary').textContent(),/Parcel hệ thống/);
    await page.locator('#saved-job').fill(native.job_id);
    await page.locator('#restore').click();
    await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Hoàn thành và lưu'));
    await page.locator('#option').selectOption('P1_only');
    await page.locator('#layer').selectOption('roads');
    assert.ok(await page.locator('#map polyline').count()>0);
    assert.match(await page.locator('#map-note').textContent(),/synthetic/);
    await page.locator('#layer').selectOption('drainage');
    assert.ok(await page.locator('#map circle').count()>0);
    checks.push('Live screening and saved native SUMO/SWMM results render with generated-network limits');
    await page.locator('#system-demo').screenshot({path:out+'/system-parcels-desktop.png'});
    await page.setViewportSize({width:390,height:844});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
    await page.locator('#system-demo').screenshot({path:out+'/system-parcels-mobile.png'});
    assert.deepEqual(errors,[]);
    checks.push('Desktop/mobile layout and no browser JavaScript errors');
    fs.writeFileSync(out+'/ui-report.json',JSON.stringify({status:'passed',checks},null,2));
    console.log(JSON.stringify({status:'passed',checks},null,2));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
