const fs=require('fs'),path=require('path'),{createRequire}=require('module');
const root=path.resolve(__dirname,'..'),req=createRequire(path.join(root,'frontend/package.json'));
const {chromium}=req('@playwright/test');
const out=path.join(root,'test-results/query-upgrade');
(async()=>{
 const evidence=JSON.parse(fs.readFileSync(path.join(out,'live-cases.json'),'utf8'));
 if(!evidence.passed)throw Error('Semantic model acceptance must pass first');
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try{
  await page.addInitScript(id=>localStorage.setItem('development-assistant-session',id),evidence.model_session_id);
  await page.goto('http://127.0.0.1:8192/',{waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Planning assistant',exact:true}).click();
  const panel=page.getByRole('complementary',{name:'Planning assistant'});
  await panel.getByText('Travel access · Goong routes',{exact:true}).waitFor();
  await panel.getByText(/Database filters applied before display limit/).waitFor();
  const old=evidence.turns.at(-1).response.route_result.id;
  const responsePromise=page.waitForResponse(r=>r.url().endsWith('/tools/route_show')&&r.request().method()==='POST');
  const button=panel.getByRole('button',{name:'Show route to hospital'}).first();
  await button.scrollIntoViewIfNeeded();await button.click();
  const response=await responsePromise;
  if(!response.ok())throw Error('Route button failed: '+response.status());
  const session=await response.json();
  if(session.route_result.id===old)throw Error('Route button did not request a new sourced route');
  if(session.route_features.features[0].geometry.type!=='LineString')throw Error('Missing route line');
  if(session.route_result.source!=='Goong Directions V2')throw Error('Missing route source');
  await panel.getByText(/Displayed route to/).scrollIntoViewIfNeeded();
  await page.waitForTimeout(2500);
  await page.screenshot({path:path.join(out,'routes-desktop.png'),fullPage:true});
  await panel.getByText('Analysis boundary',{exact:true}).click();
  await panel.getByText(/viewport · /).waitFor();
  const downloadPromise=page.waitForEvent('download');
  await panel.getByRole('button',{name:'Download evidence report'}).click();
  await (await downloadPromise).saveAs(path.join(out,'report.md'));
  const report=fs.readFileSync(path.join(out,'report.md'),'utf8');
  if(!report.includes('Goong Distance Matrix V2')||!report.includes('Goong Directions V2'))throw Error('Export lost route evidence');
  await page.setViewportSize({width:390,height:844});
  await panel.getByText('Travel access · Goong routes',{exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:path.join(out,'routes-mobile.png'),fullPage:true});
  const searchPage=await browser.newPage({viewport:{width:1280,height:900}});
  searchPage.on('pageerror',e=>errors.push(e.message));
  await searchPage.goto('http://127.0.0.1:8192/',{waitUntil:'domcontentloaded'});
  await searchPage.getByRole('searchbox',{name:'Search places'}).fill('hẻm 114 Trần Quốc Tuấn Gò Vấp');
  await searchPage.getByRole('button',{name:/Hẻm 114 Trần Quốc Tuấn,/}).first().click({timeout:20000});
  await searchPage.getByRole('complementary',{name:'Place details'}).waitFor();
  await searchPage.getByRole('button',{name:'Planning assistant',exact:true}).click();
  const second=searchPage.getByRole('complementary',{name:'Planning assistant'});
  let selectedBinding;
  await searchPage.route('**/api/v1/agent/chat',async route=>{
   const body=route.request().postDataJSON();selectedBinding=body.workspace.selected_place;
   await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({...session,answer:'Test of the selected-place request binding.',messages:[...session.messages,{role:'assistant',content:'Test of the selected-place request binding.'}],trace:[]})});
  });
  await second.getByRole('textbox').fill('Analyze the selected place');
  const capturedResponse=searchPage.waitForResponse(r=>r.url().endsWith('/api/v1/agent/chat')&&r.request().method()==='POST');
  await second.getByRole('button',{name:'Send',exact:true}).click();
  await capturedResponse;
  if(!selectedBinding||Math.abs(selectedBinding.latitude-evidence.selected_place.latitude)>.00001)throw Error('Search-selected place missing from agent workspace binding');
  if(errors.length)throw Error(errors.join('; '));
  const result={passed:true,checks:['database_count_caption','route_button_real_api','route_geometry','route_source','scope_kind_visible','export_route_sources','mobile_panel','selected_web_place_binding','no_page_errors']};
  fs.writeFileSync(path.join(out,'browser-result.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
 }finally{await browser.close();}
})().catch(e=>{console.error(String(e));process.exit(1);});
