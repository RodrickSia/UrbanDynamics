// Actual API/worker and saved native run; no mocked simulation results.
const {chromium} = require('../.runtime/ui-check/node_modules/playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
process.chdir(path.resolve(__dirname, '..'));
(async () => {
  const base = process.env.PLANNING_API_URL || 'http://127.0.0.1:8005';
  const evidence = name => path.join(process.env.PLANNING_EVIDENCE_DIR || 'test-results/planning-studies', name);
  const native = JSON.parse(fs.readFileSync(evidence('http-native-report.json'), 'utf8'));
  const report = {base, checks: []};
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1360, height: 980}});
    // Background launchers can return before Uvicorn binds its port. Poll the
    // intended endpoint; do not restart a healthy process on observation delay.
    let ready = false;
    for(let attempt=0;attempt<40;attempt++){
      try {const response=await page.request.get(base+'/api/v1/planning/presets',{timeout:1000});if(response.ok()){ready=true;break;}}catch{}
      await new Promise(resolve=>setTimeout(resolve,250));
    }
    assert.ok(ready, 'Planning API did not become ready');
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(base+'/simulation/planning');
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Đã nạp mẫu'));
    await page.locator('#preflight').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Sẵn sàng:'));
    await page.locator('#run').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'), {}, {timeout: 45000});
    assert.equal(await page.locator('#metrics tbody tr').count(), 17);
    const normalizedCount = await page.locator('#normalized tbody tr').count();
    assert.equal(normalizedCount, 9);
    assert.match(await page.locator('#normalization-note').textContent(), /không chia cho dân số nền/);
    assert.match(await page.locator('#ranking').textContent(), /Pareto/);
    report.checks.push('Live screening job, immutable saved result and explicit criteria');
    await page.locator('#layer').selectOption('school');
    const firstMap = await page.locator('#map').innerHTML();
    await page.locator('#option').selectOption('C_only');
    assert.notEqual(await page.locator('#map').innerHTML(), firstMap);
    report.checks.push('Option selection changes school allocation layer');
    await page.locator('#saved-job').fill(native.runs.find(r => r.mode === 'cumulative').job_id);
    await page.locator('#restore').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'));
    await page.locator('#option').selectOption('ABC');
    assert.equal(await page.locator('#study-mode').inputValue(), 'cumulative');
    assert.match(await page.locator('#preset-description').textContent(), /đầu vào đã lưu/);
    assert.equal(await page.locator('#metrics tbody tr').count(), 31);
    assert.equal(await page.locator('#capacities .bad').count(), 3);
    await page.locator('#normalization-details').evaluate(el => el.open = true);
    assert.equal(await page.locator('#normalized tbody tr').count(), 11);
    assert.match(await page.locator('#normalized').textContent(), /0,00232/);
    await page.locator('#normalization-details').screenshot({path: evidence('planning-normalization.png')});
    await page.locator('#normalization-details').evaluate(el => el.open = false);
    assert.match(await page.locator('#phases').textContent(), /phase_3/);
    report.checks.push('Native result reload, portfolio constraints, phases and paired traffic/drainage metrics');
    await page.locator('#layer').selectOption('roads');
    assert.ok(await page.locator('#map polyline').count() > 0);
    await page.locator('#layer').selectOption('drainage');
    assert.ok(await page.locator('#map circle').count() > 0);
    await page.locator('#layer').selectOption('shadow');
    assert.ok(await page.locator('#map path').count() > 4);
    report.checks.push('Native roads, SWMM nodes and union shadow GeoJSON render');
    await page.locator('#layer').selectOption('drainage_links');
    await page.locator('#drainage-sample').selectOption('20');
    assert.ok(await page.locator('#map polyline').count() > 0);
    assert.match(await page.locator('#map').innerHTML(), /flow_m3_s/);
    assert.match(await page.locator('#map').innerHTML(), /"minute":21/);
    const at21 = await page.locator('#map').innerHTML();
    await page.locator('#drainage-sample').selectOption('40');
    assert.notEqual(await page.locator('#map').innerHTML(), at21);
    await page.locator('#layer').selectOption('roads');
    assert.equal(await page.locator('#traffic-seed').inputValue(), '2026');
    assert.match(await page.locator('#map').innerHTML(), /sampled_peak_queue_m/);
    const downloadUrl = new URL(await page.locator('#download').getAttribute('href'), base);
    const runUrl = downloadUrl.href.replace(/\/artifacts$/, '');
    const nodeResponse = await page.request.get(runUrl+'/map?option_id=ABC&name=drainage&drainage_sample=20');
    assert.equal(nodeResponse.status(), 200);
    const nodeMap = await nodeResponse.json();
    assert.equal(nodeMap.time_window.sample_index, 20);
    assert.ok(nodeMap.features.every(f => Number.isFinite(f.properties.depth_m)));
    const badSample = await page.request.get(runUrl+'/map?option_id=ABC&name=drainage_links&drainage_sample=9999');
    assert.equal(badSample.status(), 422);
    report.checks.push('Live SWMM link geometry and minute selectors, SUMO queue tooltip and seed selector; API sample values and invalid sample rejected');
    const download = await page.request.get(new URL(await page.locator('#download').getAttribute('href'), base).href);
    assert.equal(download.status(), 200);
    assert.match(download.headers()['content-type'], /zip/);
    report.checks.push('Download actual native artifact ZIP');
    await page.screenshot({path: evidence('planning-desktop.png'), fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    await page.screenshot({path: evidence('planning-mobile.png'), fullPage: true});
    const overflow = await page.evaluate(() => ({width: document.documentElement.scrollWidth, viewport: innerWidth,
      outside: [...document.querySelectorAll('main *')].filter(el => !el.closest('.scroll')).map(el => ({tag:el.tagName,id:el.id,right:el.getBoundingClientRect().right})).filter(el => el.right > innerWidth)}));
    assert.ok(overflow.width <= overflow.viewport, JSON.stringify(overflow));
    report.checks.push('Mobile 390px without horizontal page overflow');
    const fixtureResponse = await page.request.get(base+'/api/v1/planning/presets');
    assert.equal(fixtureResponse.status(), 200);
    const fixtures = await fixtureResponse.json();
    const retryInput = fixtures.site_selection;
    retryInput.projects = retryInput.projects.slice(0, 1);
    retryInput.options = retryInput.options.slice(0, 1);
    retryInput.conditions = {traffic_hours: [18], seeds: [2026,2027]};
    const savedResponse = await page.request.post(base+'/api/v1/planning/studies', {data: retryInput});
    assert.equal(savedResponse.status(), 201);
    const saved = await savedResponse.json();
    const queuedResponse = await page.request.post(`${base}/api/v1/planning/studies/${saved.id}/runs`,
      {data: {mode: 'native', idempotency_key: 'ui-retry-'+Date.now()}});
    assert.equal(queuedResponse.status(), 202);
    const queued = await queuedResponse.json();
    const cancelled = await page.request.post(`${base}/api/v1/planning/jobs/${queued.id}/cancel`);
    assert.equal(cancelled.status(), 200);
    await page.locator('#saved-job').fill(queued.id);
    await page.locator('#restore').click();
    await page.waitForFunction(() => !document.querySelector('#retry').disabled, {}, {timeout: 30000});
    assert.ok(await page.locator('#results').isHidden());
    await page.locator('#retry').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'), {}, {timeout: 45000});
    const completedResponse = await page.request.get(`${base}/api/v1/planning/jobs/${queued.id}`);
    const completed = await completedResponse.json();
    assert.equal(completed.status, 'succeeded');
    assert.ok(completed.result_id);
    assert.equal(JSON.parse(await page.locator('#input').inputValue()).projects.length, 1);
    await page.locator('#layer').selectOption('roads');
    await page.locator('#traffic-seed').selectOption('2027');
    assert.match(await page.locator('#map-note').textContent(), /seed 2027/);
    const pairedMap = await page.request.get(`${base}/api/v1/planning/runs/${completed.result_id}/map?option_id=A_only&name=roads&hour=18&seed=2027&interval=4`);
    assert.equal(pairedMap.status(), 200);
    assert.equal((await pairedMap.json()).time_window.seed, 2027);
    report.checks.push('Cancelled native job reload and retry through the actual UI; original saved input and a complete native run');
    await page.locator('#study-mode').selectOption('rehousing');
    await page.locator('#load-preset').click();
    await page.locator('#run-mode').selectOption('screening');
    await page.locator('#run').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'), {}, {timeout: 45000});
    await page.locator('#option').selectOption('ABC');
    assert.match(await page.locator('#population-ledger').textContent(), /thay đổi ròng 200/);
    assert.match(await page.locator('#population-ledger').textContent(), /nội vùng đã khai báo: 100/);
    assert.match(await page.locator('#population-ledger').textContent(), /chưa giải thích: 0/);
    assert.equal(await page.locator('#ledger tbody tr').count(), 15);
    await page.locator('#option').selectOption('A_only');
    assert.match(await page.locator('#ledger-note').textContent(), /Chưa rõ nơi đến của 100/);
    await page.locator('#option').selectOption('ABC');
    await page.locator('#ledger-details').evaluate(el => el.open = true);
    await page.screenshot({path: evidence('planning-rehousing.png'), fullPage: true});
    report.checks.push('Live rehousing fixture: 100 internally relocated, net 200 new regional residents, explicit load ledger and unknown destination when A clears alone');
    assert.equal(await page.locator('#coverage tbody tr').count(), 6);
    assert.match(await page.locator('#manifest-summary').textContent(), /nguồn đầu vào được đóng băng/);
    assert.match(await page.locator('#coverage').textContent(), /chưa có polygon khảo sát/);
    report.checks.push('Frozen source manifest and per-module coverage visible, including nonspatial drainage/utility limits');
    await page.locator('#study-mode').selectOption('inclusive');
    await page.locator('#load-preset').click();
    await page.locator('#run').click();
    await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'), {}, {timeout: 45000});
    await page.locator('#option').selectOption('ABC');
    assert.match(await page.locator('#population-ledger').textContent(), /thay đổi ròng 200/);
    assert.match(await page.locator('#background-normalization').textContent(), /đầu vào 1\.300; sau tách 1\.200/);
    assert.match(await page.locator('#background-normalization').textContent(), /1 parcel vật lý/);
    report.checks.push('Inclusive snapshot raw 1300 becomes background 1200; final regional growth remains 200 without repeated phase subtraction');
    const singlePath = evidence('single/http-native-report.json');
    if(fs.existsSync(singlePath)){
      const single = JSON.parse(fs.readFileSync(singlePath, 'utf8'));
      await page.locator('#study-mode').selectOption('single_site');
      await page.locator('#load-preset').click();
      assert.equal(JSON.parse(await page.locator('#input').inputValue()).projects.length, 1);
      await page.locator('#saved-job').fill(single.runs[0].job_id);
      await page.locator('#restore').click();
      await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'));
      assert.equal(await page.locator('#study-mode').inputValue(), 'single_site');
      assert.equal(JSON.parse(await page.locator('#input').inputValue()).projects.length, 1);
      await page.locator('#option').selectOption('A_only');
      await page.locator('#layer').selectOption('roads');
      assert.ok(await page.locator('#map polyline').count() > 0);
      report.checks.push('Single-site preset and actual native job restore on shared regional context; project and roads layer preserved');
    }
    if (fs.existsSync(evidence('http-uncertainty-report.json'))) {
      const sampled = JSON.parse(fs.readFileSync(evidence('http-uncertainty-report.json'), 'utf8'));
      await page.locator('#saved-job').fill(sampled.runs[0].job_id);
      await page.locator('#restore').click();
      await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'));
      await page.locator('#option').selectOption('C_only');
      await page.locator('#assumption-case').selectOption('high');
      assert.equal(await page.locator('#option').inputValue(), 'C_only');
      assert.equal(JSON.parse(await page.locator('#audit').textContent()).conditions.level, 'high');
      await page.locator('#assumption-case').selectOption('low');
      assert.equal(await page.locator('#option').inputValue(), 'C_only');
      assert.equal(JSON.parse(await page.locator('#audit').textContent()).conditions.level, 'low');
      assert.match(await page.locator('#stability').textContent(), /Kết luận độ ổn định/);
      assert.equal(JSON.parse(await page.locator('#audit').textContent()).seed_analysis.seed_suite.length, 3);
      report.checks.push('Actual uncertainty run reload, case switching, three paired seeds and overall stability warning');
    }
    if(process.env.PLANNING_PORTFOLIO_EVIDENCE_DIR){
      const portfolio = JSON.parse(fs.readFileSync(path.join(process.env.PLANNING_PORTFOLIO_EVIDENCE_DIR, 'portfolio-report.json'), 'utf8'));
      for(const record of portfolio.runs){
        await page.locator('#saved-job').fill(record.job_id);
        await page.locator('#restore').click();
        await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'));
        assert.equal(await page.locator('#study-mode').inputValue(), 'cumulative');
        assert.equal(JSON.parse(await page.locator('#input').inputValue()).options.length, 7);
        await page.locator('#option').selectOption('phase_1');
        const first = JSON.parse(await page.locator('#input').inputValue()).phases[0].active_project_ids;
        assert.deepEqual(first, record.order === 'A-first' ? ['A'] : ['B']);
        await page.locator('#option').selectOption('phase_3');
        assert.equal(await page.locator('#capacities .bad').count(), 3);
        await page.locator('#layer').selectOption('drainage_links');
        await page.locator('#drainage-sample').selectOption('20');
        assert.ok(await page.locator('#map polyline').count() > 0);
        await page.screenshot({path: path.join(process.env.PLANNING_PORTFOLIO_EVIDENCE_DIR, record.order+'-browser.png'), fullPage: true});
      }
      report.checks.push('Both saved eight-state commissioning orders open on map, preserve first project, show phase-three capacity breaches and native SWMM links');
    }
    if(process.env.PLANNING_MISSING_EVIDENCE_DIR){
      const missing = JSON.parse(fs.readFileSync(path.join(process.env.PLANNING_MISSING_EVIDENCE_DIR, 'http-report.json'), 'utf8'));
      await page.locator('#saved-job').fill(missing.runs.find(r => r.mode === 'native').job_id);
      await page.locator('#restore').click();
      await page.waitForFunction(() => document.querySelector('#status').textContent.includes('Hoàn thành và lưu'));
      await page.locator('#option').selectOption('AB');
      const power = page.locator('#metrics tbody tr').filter({hasText:'Đỉnh điện chung'});
      const cells = await power.locator('td').allTextContents();
      assert.deepEqual(cells.slice(1,4), ['Chưa biết','Chưa biết','Chưa biết']);
      assert.equal(cells[5], 'insufficient_data');
      const audit = JSON.parse(await page.locator('#audit').textContent());
      const effect = audit.interaction_effects.find(e => e.active_project_ids.join(',') === 'A,B');
      assert.equal(effect.metrics.power_peak_kw, null);
      assert.equal(effect.comparability_by_metric.power_peak_kw, 'insufficient_data');
      await page.screenshot({path:path.join(process.env.PLANNING_MISSING_EVIDENCE_DIR, 'unknown-browser.png'),fullPage:true});
      report.checks.push('Actual unknown native job reload shows null before/after/delta and unavailable portfolio interaction; ranking remains blocked');
    }
    await page.locator('details').first().evaluate(el => el.open = true);
    await page.locator('#input').fill('{invalid');
    assert.ok(await page.locator('#results').isHidden());
    await page.locator('#preflight').click();
    assert.equal(await page.locator('#status').getAttribute('data-error'), 'true');
    assert.deepEqual(errors, []);
    report.checks.push('Edited input hides stale result; invalid JSON reported; no browser exceptions');
    report.status = 'passed';
  } finally {
    await browser.close();
    fs.writeFileSync(evidence('ui-report.json'), JSON.stringify(report, null, 2));
  }
  console.log(JSON.stringify(report, null, 2));
})().catch(error => {console.error(error); process.exitCode = 1;});
